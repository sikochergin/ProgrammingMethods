## @file generator.py
#  @brief Генератор CSV-файлов для лабораторной работы №2.
#
#  Скрипт создает наборы данных о служащих воинского полка.
#  Полученные CSV-файлы используются далее в C++ программе для проверки
#  и сравнения алгоритмов сортировки.
#
#  Все файлы сохраняются в папку mil_csv_folder.

import csv
import random
from pathlib import Path

## @brief Название папки для сохранения CSV-файлов.
FOLDER = Path("mil_csv_folder")

## @brief Размеры генерируемых наборов данных.
#
#  от 100 до 1000000 элементов. В данном варианте используется 17 наборов.
DATA_SIZES = [100, 200, 500, 1000, 2000, 5000, 10000, 20000, 30000, 40000, 50000, 65000, 80000, 100000, 250000, 500000, 1000000]

## @brief Фамилии для генерации ФИО служащих.
LAST_NAMES = [
    "Иванов", "Петров", "Сидоров", "Смирнов", "Кузнецов", "Попов",
    "Васильев", "Соколов", "Михайлов", "Новиков", "Фёдоров", "Морозов",
    "Кочергин", "Алексеев", "Лебедев", "Семёнов", "Егоров", "Павлов",
    "Козлов", "Степанов", "Николаев", "Орлов", "Андреев", "Макаров",
    "Никитин", "Захаров", "Зайцев", "Соловьёв", "Борисов", "Яковлев",
]

## @brief Имена для генерации ФИО служащих.
FIRST_NAMES = [
    "Александр", "Дмитрий", "Максим", "Сергей", "Андрей", "Алексей",
    "Артём", "Илья", "Кирилл", "Михаил", "Никита", "Матвей",
    "Роман", "Егор", "Иван", "Денис", "Евгений", "Степан",
    "Павел", "Константин", "Олег", "Виктор", "Юрий",
]

## @brief Отчества для генерации ФИО служащих.
PATRONYMICS = [
    "Александрович", "Дмитриевич", "Максимович", "Сергеевич",
    "Андреевич", "Алексеевич", "Ильич", "Кириллович", "Михайлович",
    "Никитич", "Романович", "Иванович", "Павлович", "Олегович",
    "Викторович", "Юрьевич",
]

## @brief Список воинских званий.
#
#  Порядок званий в этом списке соответствует их старшинству.
#  Такой же порядок будет использоваться в C++ коде при перегрузке
#  операторов сравнения.
RANKS = [
    "рядовой",
    "сержант",
    "прапорщик",
    "лейтенант",
    "капитан",
    "майор",
    "полковник",
]

## @brief Создает одну запись о служащем.
#
#  Запись содержит ФИО, звание, номер роты и возраст.
#
#  @return Список значений одной строки CSV-файла.
def make_soldier_record():
    return [
        f"{random.choice(LAST_NAMES)} {random.choice(FIRST_NAMES)} {random.choice(PATRONYMICS)}", #ФИО
        random.choice(RANKS), #Звание
        random.randint(1, 12), #номер роты
        random.randint(18, 60), #Возраст
    ]

## @brief Создает один CSV-файл заданного размера.
#
#  В первой строке файла записываются названия полей.
#  Далее записываются случайно сгенерированные данные о служащих.
#
#  @param records_count Количество записей, которое нужно создать.
#  @return Путь к созданному CSV-файлу.
def create_csv_file(size):
    FOLDER.mkdir(exist_ok=True)

    file_name = f"soldiers_{size}.csv"
    file_path = FOLDER / file_name

    with file_path.open("w", encoding="utf-8", newline="") as file:
        writer = csv.writer(file)
        writer.writerow(["fullName", "rank", "companyNumber", "age"])

        for _ in range(size):
            writer.writerow(make_soldier_record())

    return file_path

## @brief Основная функция программы.
#
#  Устанавливает начальное значение генератора случайных чисел
#  и создает CSV-файлы для всех размеров из DATASET_SIZES.
def main():
    random.seed(42)

    print("Генерация началась")

    for size in DATA_SIZES:
        file_path = create_csv_file(size)
        print(f"Создан файл: {file_path}")

    print("Генерация закончена")


if __name__ == "__main__":
    main()